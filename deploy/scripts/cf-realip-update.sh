#!/bin/bash
# Sync Cloudflare's published IP ranges into an nginx real_ip config.
#
# Why: once the zone is proxied (orange cloud), every request reaching the
# origin comes from a Cloudflare edge, so nginx logs and rate limits see
# Cloudflare's IPs instead of the visitor's. CF puts the real client address
# in the CF-Connecting-IP header; real_ip tells nginx to trust that header
# when - and only when - the peer is one of these ranges.
#
# Run manually after the first install, then daily via cf-realip.timer.

set -euo pipefail

OUT=/etc/nginx/conf.d/cloudflare-realip.conf
BACKUP="${OUT}.bak"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

fetch() {
    curl -fsS --max-time 20 "$1"
}

V4="$(fetch https://www.cloudflare.com/ips-v4)" || { echo "ERROR: cannot fetch ips-v4"; exit 1; }
V6="$(fetch https://www.cloudflare.com/ips-v6)" || { echo "ERROR: cannot fetch ips-v6"; exit 1; }

ALL="$(printf '%s\n%s\n' "$V4" "$V6" | tr -d '\r' | grep '/' | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
COUNT="$(printf '%s\n' "$ALL" | wc -l)"

# Paranoia: an empty or truncated list would silently stop trusting real IPs,
# and a garbage response would break nginx. Refuse to write either.
if [ "$COUNT" -lt 10 ]; then
    echo "ERROR: suspicious range count ($COUNT), refusing to update"
    exit 1
fi

{
    echo "# Generated by /usr/local/bin/cf-realip-update.sh - do not edit by hand."
    echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)  ranges: $COUNT"
    printf '%s\n' "$ALL" | awk '{print "set_real_ip_from " $1 ";"}'
    echo "real_ip_header CF-Connecting-IP;"
    echo "real_ip_recursive on;"
} > "$TMP"

if [ -f "$OUT" ]; then
    cp -a "$OUT" "$BACKUP"
fi

install -m 644 "$TMP" "$OUT"

if nginx -t >/dev/null 2>&1; then
    systemctl reload nginx
    echo "OK: $COUNT ranges written, nginx reloaded"
else
    echo "ERROR: nginx -t failed, rolling back"
    if [ -f "$BACKUP" ]; then
        mv "$BACKUP" "$OUT"
        nginx -t >/dev/null 2>&1 && systemctl reload nginx || true
    fi
    exit 1
fi
